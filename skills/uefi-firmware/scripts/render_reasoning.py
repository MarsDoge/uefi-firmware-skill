#!/usr/bin/env python3
"""Generate human and agent views from maps/reasoning.json (stdlib only)."""
import json
import html
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'maps/reasoning.json').read_text())
nodes = data['nodes']
ids = [n['id'] for n in nodes]
assert len(ids) == len(set(ids))
for a, b in data['edges']:
    assert a in ids and b in ids
for entry in nodes + data['routes']:
    for ref in entry['refs']:
        assert (root / ref).is_file(), ref
esc = html.escape
svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="1020" viewBox="0 0 1200 1020" role="img" aria-labelledby="title desc">',
       '<title id="title">UEFI Firmware 工程决策流程</title><desc id="desc">定义问题、定位职责、收集依据、提出判断、验证目标、输出沉淀；验证不足时返回定位。</desc>',
       '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#1d4ed8"/></marker></defs>',
       '<rect width="1200" height="1020" fill="#f8fafc"/>',
       '<g font-family="Noto Sans CJK SC,Microsoft YaHei,sans-serif">',
       '<text x="60" y="60" fill="#0f172a" font-size="30">UEFI Firmware · 从问题到证据</text>',
       '<text x="60" y="98" fill="#475569" font-size="17">同一流程，两种入口：人看关系，Agent 按需查阅</text>']
positions = [(60,145),(440,145),(820,145),(820,425),(440,425),(60,425)]
coords = dict(zip(ids, positions))
for a,b in data['edges']:
    x,y=coords[a]; xx,yy=coords[b]
    if a=='verify' and b=='locate':
        path=f'M {x+165} {y} L {xx+165} {yy+190}'
        dash=' stroke-dasharray="6 6"'
    elif y==yy:
        start=x+330 if xx>x else x
        end=xx if xx>x else xx+330
        path=f'M {start} {y+95} L {end} {yy+95}'
        dash=''
    else:
        path=f'M {x+165} {y+190} L {xx+165} {yy}'
        dash=''
    svg.append(f'<path d="{path}" fill="none" stroke="#1d4ed8" stroke-width="2"{dash} marker-end="url(#arrow)"/>')
svg.append('<text x="618" y="385" fill="#92400e" font-size="16">证据不足 / 假设不成立</text>')
for n,(x,y) in zip(nodes,positions):
    svg.extend([f'<rect x="{x}" y="{y}" width="330" height="190" rx="16" fill="#ffffff" stroke="#cbd5e1"/>',
                f'<text x="{x+20}" y="{y+40}" fill="#1d4ed8" font-size="22">{esc(n["title"])}</text>'])
    question=n['question']
    # Short bounded lines keep CJK labels inside each card.
    for i,line in enumerate([question[j:j+16] for j in range(0,len(question),16)]):
        svg.append(f'<text x="{x+20}" y="{y+78+i*27}" fill="#0f172a" font-size="17">{esc(line)}</text>')
    svg.append(f'<text x="{x+20}" y="{y+157}" fill="#475569" font-size="15">产出：{esc(n["output"])}</text>')
svg.extend(['<text x="60" y="690" fill="#0f172a" font-size="23">始终区分四层依据</text>'])
for i,label in enumerate(['规范契约','edk2 实现','平台策略','工具行为']):
    x=60+i*285
    svg.append(f'<rect x="{x}" y="715" width="255" height="60" rx="12" fill="#ecfdf5"/><text x="{x+25}" y="753" fill="#065f46" font-size="21">{label}</text>')
for i,text in enumerate(['人：先看全局，再到预览页展开步骤与参考。','Agent：先读 SKILL.md，按问题选参考；无须识图，也不必读完整库。','边界：编译通过 ≠ 运行验证；案例成立 ≠ 通用标准；缺少证据 ≠ 已证明错误。','图中步骤按任务裁剪：概念解释无需强行构建，运行主张必须有对应执行证据。']):
    svg.append(f'<text x="60" y="{830+i*39}" fill="#334155" font-size="18">{esc(text)}</text>')
svg.append('</g></svg>')
svg='\n'.join(svg)
ET.fromstring(svg)
(root/'maps/reasoning.svg').write_text(svg)
md=['<!-- Generated by scripts/render_reasoning.py; edit maps/reasoning.json. -->','# Decision Flow / 工程决策流程','',data['subtitle'],'','Read only the references needed for the current question. This is an explicit engineering workflow, not a request to expose private model reasoning.','']
for n in nodes:
    md.extend([f'## {n["title"]} / {n["id"]}', '',n['question'],'',n['action'],'',f'Output: {n["output"]}','', 'Read: '+', '.join('['+Path(r).name+']('+Path(r).name+')' for r in n['refs']),''])
md.extend(['## Routing / 按问题查阅',''])
for r in data['routes']:
    md.append('- '+r['query']+' → '+', '.join('['+Path(f).name+']('+Path(f).name+')' for f in r['refs']))
md.extend(['','## Transitions / 路径','']+[f'- {a} → {b}'+(' (insufficient evidence / unsupported hypothesis)' if a=='verify' and b=='locate' else '') for a,b in data['edges']])
(root/'references/decision-flow.md').write_text('\n'.join(md)+'\n')
parts=['<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>UEFI Skill 流程预览</title><style>body{margin:0;background:#f8fafc;color:#172033;font:17px/1.7 system-ui,sans-serif}main{max-width:1200px;margin:auto;padding:16px}svg{width:100%;height:auto}details{background:#ffffff;border:1px solid #cbd5e1;border-radius:12px;padding:18px;margin:14px 0}summary{cursor:pointer;color:#1d4ed8;font-size:21px}a{color:#065f46}code{color:#92400e}footer{color:#475569;padding:24px 0}</style><main>',svg,'<h2>展开步骤，查看动作与资料</h2>']
for n in nodes:
    parts.extend(['<details><summary>'+esc(n['title'])+'</summary><p>'+esc(n['action'])+'</p><p>产出：'+esc(n['output'])+'</p><p>参考：'+' · '.join('<a href="../'+esc(r)+'">'+esc(Path(r).name)+'</a>' for r in n['refs'])+'</p></details>'])
parts.extend(['<h2>Agent 的阅读入口</h2><p>读取 SKILL.md → 按问题选择参考 → 如需完整流程，读取 references/decision-flow.md。JSON 是维护与工具接口，不要求 Agent 每次读取。</p><footer>源文件：maps/reasoning.json。SVG、此预览和 decision-flow.md 由同一脚本生成。案例是方法示例，不代表本轮完成了固件实测。</footer></main></html>'])
(root/'maps/preview.html').write_text('\n'.join(parts))
print(f'Validated {len(nodes)} nodes, {len(data["edges"])} edges and all reference targets; generated SVG, HTML, Markdown.')
